-- HoopLoop Version 7 online database
-- Run this entire file in a NEW Supabase project's SQL Editor.
-- It creates accounts/profile support, daily scores, practice records,
-- friends, and realtime head-to-head race tables/functions.

create extension if not exists citext;
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username citext not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (username::text ~ '^[A-Za-z0-9_]{3,18}$')
);

create table if not exists public.daily_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  puzzle_date date not null,
  puzzle_signature text not null,
  time_ms integer not null check (time_ms between 1500 and 600000),
  hints_used integer not null default 0 check (hints_used between 0 and 30),
  round_splits jsonb not null default '[]'::jsonb,
  submitted_at timestamptz not null default now(),
  unique (user_id, puzzle_date)
);

create table if not exists public.practice_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  difficulty text not null check (difficulty in ('rookie','starter','allstar','mvp')),
  round_count integer not null check (round_count between 1 and 1000),
  correct_count integer not null check (correct_count between 0 and round_count),
  time_ms integer not null check (time_ms between 1 and 86400000),
  best_round_ms integer,
  hints_used integer not null default 0 check (hints_used >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.friendships (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references public.profiles(id) on delete cascade,
  addressee_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  constraint friendships_not_self check (requester_id <> addressee_id)
);

create unique index if not exists friendships_unique_pair
  on public.friendships (least(requester_id, addressee_id), greatest(requester_id, addressee_id));

create table if not exists public.race_matches (
  id uuid primary key default gen_random_uuid(),
  host_id uuid not null references public.profiles(id) on delete cascade,
  opponent_id uuid references public.profiles(id) on delete set null,
  winner_id uuid references public.profiles(id) on delete set null,
  match_type text not null check (match_type in ('random','friend')),
  status text not null default 'waiting' check (status in ('waiting','invited','active','finished','cancelled')),
  rounds jsonb not null,
  starts_at timestamptz,
  created_at timestamptz not null default now(),
  finished_at timestamptz,
  constraint race_rounds_three check (jsonb_typeof(rounds) = 'array' and jsonb_array_length(rounds) = 3),
  constraint race_not_self check (opponent_id is null or host_id <> opponent_id)
);

create table if not exists public.race_progress (
  match_id uuid not null references public.race_matches(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  round_index integer not null default 0 check (round_index between 0 and 3),
  elapsed_ms integer check (elapsed_ms is null or elapsed_ms between 0 and 3600000),
  hints_used integer not null default 0 check (hints_used >= 0),
  finished_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (match_id, user_id)
);

create index if not exists daily_scores_date_time_idx on public.daily_scores (puzzle_date, time_ms, submitted_at);
create index if not exists daily_scores_user_idx on public.daily_scores (user_id, puzzle_date desc);
create index if not exists practice_sessions_user_idx on public.practice_sessions (user_id, created_at desc);
create index if not exists friendships_requester_idx on public.friendships (requester_id, status);
create index if not exists friendships_addressee_idx on public.friendships (addressee_id, status);
create index if not exists race_matches_waiting_idx on public.race_matches (match_type, status, created_at);
create index if not exists race_matches_opponent_idx on public.race_matches (opponent_id, status, created_at desc);
create index if not exists race_progress_match_idx on public.race_progress (match_id, updated_at);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

