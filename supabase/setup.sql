-- Daily scoring RPC: one official score per user/date.
create or replace function public.submit_daily_score(
  p_puzzle_date date,
  p_puzzle_signature text,
  p_time_ms integer,
  p_hints_used integer,
  p_round_splits jsonb
)
returns public.daily_scores
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  saved public.daily_scores;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  if p_puzzle_date is null or length(trim(coalesce(p_puzzle_signature, ''))) < 5 then
    raise exception 'Invalid puzzle.';
  end if;
  if p_time_ms < 1500 or p_time_ms > 600000 then raise exception 'Invalid completion time.'; end if;
  if p_hints_used < 0 or p_hints_used > 30 then raise exception 'Invalid hint count.'; end if;
  if jsonb_typeof(p_round_splits) <> 'array' or jsonb_array_length(p_round_splits) <> 3 then
    raise exception 'Three round splits are required.';
  end if;

  insert into public.daily_scores (user_id, puzzle_date, puzzle_signature, time_ms, hints_used, round_splits)
  values (uid, p_puzzle_date, upper(p_puzzle_signature), p_time_ms, p_hints_used, p_round_splits)
  on conflict (user_id, puzzle_date) do nothing
  returning * into saved;

  if saved.id is null then
    raise exception 'You already have an official score for this daily puzzle.';
  end if;
  return saved;
end;
$$;

create or replace function public.send_friend_request_by_username(p_username text)
returns public.friendships
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  target_id uuid;
  existing public.friendships;
  result public.friendships;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  select id into target_id from public.profiles where username = p_username::citext;
  if target_id is null then raise exception 'Username not found.'; end if;
  if target_id = uid then raise exception 'You cannot add yourself.'; end if;

  select * into existing from public.friendships
  where least(requester_id, addressee_id) = least(uid, target_id)
    and greatest(requester_id, addressee_id) = greatest(uid, target_id)
  limit 1;

  if existing.id is not null then
    if existing.status = 'accepted' then raise exception 'You are already friends.'; end if;
    if existing.status = 'pending' then raise exception 'A friend request is already pending.'; end if;
    update public.friendships
      set requester_id = uid, addressee_id = target_id, status = 'pending', created_at = now(), responded_at = null
      where id = existing.id returning * into result;
    return result;
  end if;

  insert into public.friendships (requester_id, addressee_id)
  values (uid, target_id) returning * into result;
  return result;
end;
$$;

create or replace function public.respond_friend_request(p_friendship_id uuid, p_accept boolean)
returns public.friendships
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  result public.friendships;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  update public.friendships
  set status = case when p_accept then 'accepted' else 'declined' end,
      responded_at = now()
  where id = p_friendship_id and addressee_id = uid and status = 'pending'
  returning * into result;
  if result.id is null then raise exception 'Friend request is no longer available.'; end if;
  return result;
end;
$$;

create or replace function public.remove_friend(p_friendship_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  removed integer;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  delete from public.friendships
  where id = p_friendship_id and uid in (requester_id, addressee_id);
  get diagnostics removed = row_count;
  return removed > 0;
end;
$$;

create or replace function public.join_random_race(p_rounds jsonb)
returns public.race_matches
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  found_match public.race_matches;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  if jsonb_typeof(p_rounds) <> 'array' or jsonb_array_length(p_rounds) <> 3 then
    raise exception 'A race requires exactly three rounds.';
  end if;

  select * into found_match
  from public.race_matches
  where match_type = 'random'
    and status = 'waiting'
    and opponent_id is null
    and host_id <> uid
    and created_at > now() - interval '5 minutes'
  order by created_at
  for update skip locked
  limit 1;

  if found_match.id is not null then
    update public.race_matches
      set opponent_id = uid, status = 'active', starts_at = now() + interval '5 seconds'
      where id = found_match.id
      returning * into found_match;
    insert into public.race_progress (match_id, user_id)
      values (found_match.id, found_match.host_id), (found_match.id, uid)
      on conflict do nothing;
    return found_match;
  end if;

  insert into public.race_matches (host_id, match_type, status, rounds)
  values (uid, 'random', 'waiting', p_rounds)
  returning * into found_match;
  insert into public.race_progress (match_id, user_id) values (found_match.id, uid);
  return found_match;
end;
$$;

create or replace function public.create_friend_race(p_friend_username text, p_rounds jsonb)
returns public.race_matches
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  friend_id uuid;
  result public.race_matches;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  if jsonb_typeof(p_rounds) <> 'array' or jsonb_array_length(p_rounds) <> 3 then
    raise exception 'A race requires exactly three rounds.';
  end if;
  select id into friend_id from public.profiles where username = p_friend_username::citext;
  if friend_id is null then raise exception 'Friend not found.'; end if;
  if not exists (
    select 1 from public.friendships f
    where f.status = 'accepted'
      and ((f.requester_id = uid and f.addressee_id = friend_id) or (f.requester_id = friend_id and f.addressee_id = uid))
  ) then raise exception 'You can only challenge accepted friends.'; end if;

  insert into public.race_matches (host_id, opponent_id, match_type, status, rounds)
  values (uid, friend_id, 'friend', 'invited', p_rounds)
  returning * into result;
  insert into public.race_progress (match_id, user_id)
    values (result.id, uid), (result.id, friend_id)
    on conflict do nothing;
  return result;
end;
$$;

create or replace function public.accept_race(p_match_id uuid)
returns public.race_matches
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  result public.race_matches;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  update public.race_matches
    set status = 'active', starts_at = now() + interval '5 seconds'
    where id = p_match_id and opponent_id = uid and status = 'invited'
    returning * into result;
  if result.id is null then raise exception 'Race invitation is no longer available.'; end if;
  return result;
end;
$$;

create or replace function public.decline_or_leave_race(p_match_id uuid)
returns public.race_matches
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  current_match public.race_matches;
  other_id uuid;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  select * into current_match from public.race_matches
    where id = p_match_id and uid in (host_id, opponent_id)
    for update;
  if current_match.id is null then raise exception 'Race not found.'; end if;

  if current_match.status = 'active' then
    other_id := case when current_match.host_id = uid then current_match.opponent_id else current_match.host_id end;
    update public.race_matches
      set status = 'finished', winner_id = other_id, finished_at = now()
      where id = p_match_id
      returning * into current_match;
  elsif current_match.status in ('waiting','invited') then
    update public.race_matches set status = 'cancelled', finished_at = now()
      where id = p_match_id returning * into current_match;
  end if;
  return current_match;
end;
$$;

create or replace function public.submit_race_progress(
  p_match_id uuid,
  p_round_index integer,
  p_elapsed_ms integer,
  p_hints_used integer,
  p_finished boolean default false
)
returns public.race_matches
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  current_match public.race_matches;
begin
  if uid is null then raise exception 'Authentication required.'; end if;
  if p_round_index < 0 or p_round_index > 3 then raise exception 'Invalid race progress.'; end if;
  if p_elapsed_ms < 0 or p_elapsed_ms > 3600000 then raise exception 'Invalid race time.'; end if;

  select * into current_match from public.race_matches
  where id = p_match_id and uid in (host_id, opponent_id)
  for update;
  if current_match.id is null then raise exception 'Race not found.'; end if;
  if current_match.status <> 'active' then return current_match; end if;
  if current_match.starts_at is null or current_match.starts_at > now() + interval '1 second' then
    raise exception 'Race has not started.';
  end if;

  insert into public.race_progress (match_id, user_id, round_index, elapsed_ms, hints_used, finished_at)
  values (p_match_id, uid, p_round_index, p_elapsed_ms, p_hints_used, case when p_finished then now() else null end)
  on conflict (match_id, user_id) do update
    set round_index = greatest(race_progress.round_index, excluded.round_index),
        elapsed_ms = greatest(coalesce(race_progress.elapsed_ms, 0), excluded.elapsed_ms),
        hints_used = greatest(race_progress.hints_used, excluded.hints_used),
        finished_at = coalesce(race_progress.finished_at, excluded.finished_at);

  if p_finished and p_round_index = 3 then
    update public.race_matches
      set winner_id = uid, status = 'finished', finished_at = now()
      where id = p_match_id and winner_id is null
      returning * into current_match;
    if current_match.id is null then
      select * into current_match from public.race_matches where id = p_match_id;
    end if;
  else
    select * into current_match from public.race_matches where id = p_match_id;
  end if;
  return current_match;
end;
$$;

