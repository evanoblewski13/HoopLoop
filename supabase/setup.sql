create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_username text;
begin
  requested_username := coalesce(new.raw_user_meta_data ->> 'username', split_part(coalesce(new.email, ''), '@', 1));

  if requested_username !~ '^[A-Za-z0-9_]{3,18}$' then
    raise exception 'Username must contain 3-18 letters, numbers, or underscores.';
  end if;

  insert into public.profiles (id, username)
  values (new.id, requested_username);

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

